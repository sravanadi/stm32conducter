#define FONT8X16_COUNT (sizeof(font8x16_table) / sizeof(font8x16_table[0]))

static inline const font8x16_glyph_t *font8x16_get_glyph(char c)
{
    /* Map lowercase to uppercase */
    if (c >= 'a' && c <= 'z') c = c - 'a' + 'A';
    for (uint32_t i = 0; i < FONT8X16_COUNT; i++) {
        if (font8x16_table[i].c == c) return &font8x16_table[i];
    }
    return &font8x16_table[0]; /* Default to space */
}

