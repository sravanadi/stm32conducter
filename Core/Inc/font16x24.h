static inline const font16x24_glyph_t *font16x24_get_glyph(char c)
{
    if (c >= 'a' && c <= 'z') c = c - 'a' + 'A';
    for (uint32_t i = 0; i < FONT16X24_COUNT; i++) {
        if (font16x24_table[i].c == c) return &font16x24_table[i];
    }
    /* Return Space if not found */
    for (uint32_t i = 0; i < FONT16X24_COUNT; i++) {
        if (font16x24_table[i].c == ' ') return &font16x24_table[i];
    }
    return &font16x24_table[0];
}

